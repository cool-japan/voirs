//! Real-time quality monitoring and dashboard for adaptive synthesis.
//!
//! This module provides comprehensive real-time monitoring of synthesis quality,
//! performance metrics, and system health with trend analysis and alerting.
//!
//! # Features
//!
//! - **Real-time Metrics**: Live tracking of quality, latency, and resource usage
//! - **Trend Analysis**: Statistical analysis of metric trends over time
//! - **Alert System**: Configurable alerts for quality degradation or anomalies
//! - **Dashboard Data**: Aggregated metrics for visualization dashboards
//! - **Historical Tracking**: Time-series data storage for analysis
//!
//! # Example
//!
//! ```no_run
//! use voirs_sdk::adaptive::monitoring::{QualityMonitor, MonitorConfig, AlertThreshold};
//!
//! #[tokio::main]
//! async fn main() -> voirs_sdk::Result<()> {
//!     let config = MonitorConfig::default()
//!         .with_sample_window(100)
//!         .with_alert_threshold(AlertThreshold::QualityDrop(0.15));
//!
//!     let monitor = QualityMonitor::new(config);
//!
//!     // Monitor will track metrics and generate alerts
//!     let dashboard = monitor.get_dashboard_data().await?;
//!     println!("Current Quality: {:.2}", dashboard.current_quality_score);
//!
//!     Ok(())
//! }
//! ```

use super::{QualityTarget, SystemMetrics};
use crate::{Result, VoirsError};
